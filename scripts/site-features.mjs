// `node scripts/site-features.mjs` (#2101): renders docs/site/features.json into website/features/index.html.
// The header and footer are copied from website/index.html (the #1935 shell), so the page never drifts from it.
// The page is committed; tests/unit/site-features.test.ts regenerates it and fails when the two differ, and holds
// the data's rules: every `today.source` exists, every `later.issue` is a whole number, no entry names a date.
import { readFileSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** Words a plan must never carry: a date, a month, a promise of timing (#2101: "Coming later", never a date). */
const NO_DATES = [
  /\b(?:19|20)\d\d\b/,
  /\b\d{1,2}(?:st|nd|rd|th)\b/,
  /\b\d{1,2}\/\d{1,2}\b/,
  /\b(?:january|february|april|june|july|august|september|october|november|december)\b/i,
  /\b(?:jan|feb|mar|apr|jun|jul|aug|sept?|oct|nov|dec)\b/i,
  /\b(?:March|May|MARCH|MAY)\b/,   // capitalised only: "may" and "march" are verbs
  /\bsoon\b/i,
  /\bwill\s+be\s+available\b/i,
];

/** Every rule the data breaks, as readable lines; empty when it is sound. `exists` answers for a repo path. */
export function featureProblems(data, exists) {
  const out = [];
  const lists = { today: data?.today, later: data?.later };
  for (const [name, list] of Object.entries(lists)) {
    if (!Array.isArray(list) || !list.length) { out.push(`${name}: not a non-empty list`); continue; }
    list.forEach((e, i) => {
      const at = `${name}[${i}] ${e?.title ?? ''}`.trim();
      for (const k of ['title', 'blurb']) if (typeof e?.[k] !== 'string' || !e[k].trim()) out.push(`${at}: no ${k}`);
      for (const k of ['title', 'blurb']) for (const re of NO_DATES) if (re.test(e?.[k] ?? '')) out.push(`${at}: ${k} matches ${re}`);
      if (name === 'today' && !(typeof e?.source === 'string' && /^(?:src|tests)\/[\w./-]+$/.test(e.source) && !e.source.includes('..') && exists(e.source))) out.push(`${at}: source ${e?.source} is not a module or test that exists`);
      if (name === 'later' && !(Number.isInteger(e?.issue) && e.issue > 0)) out.push(`${at}: issue ${e?.issue} is not an issue number`);
    });
  }
  return out;
}

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const cut = (html, from, to) => {
  const a = html.indexOf(from), b = html.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error(`website/index.html: no ${from} … ${to}`);
  return html.slice(a, b + to.length);
};
const facts = list => list.map(e => `          <div><dt>${esc(e.title)}</dt><dd>${esc(e.blurb)}</dd></div>`).join('\n');

const TITLE = 'Sharpwise features: what the game does today, and what is coming later';
const DESCRIPTION = 'What Sharpwise does today: missions, Sky Storm, Ninja Duel, stickers, certificates, a grown-ups\' area, read-aloud and offline play. And what is coming later.';
const PAGE_URL = 'https://sharpwise.co.uk/features/';

