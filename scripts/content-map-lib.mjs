// Content map (#2031): the pure half. Given the registry and the strand table it returns the two generated
// files as strings, so `scripts/content-map.mjs` (writes them) and `tests/unit/content-map.test.ts` (fails on
// drift) run the very same code. No file or registry access here.

const mulberry = (seed) => () => {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};

/** Does any card this topic draws carry a picture? A fixed-seed sample, so the answer is the same on every run. */
function drawsVisual(topic) {
  const rng = mulberry(2031);
  for (const d of [1, 2, 3]) for (let i = 0; i < 12; i++) if (topic.gen(d, rng).visual) return true;
  return false;
}

const modeOf = (t) => (t.input === 'tracing' ? 'tracing' : t.solo ? 'solo' : t.drill ? 'drill' : 'mixed');
const howOf = (t) => (t.input === 'tracing' ? 'Traces the letter' : t.input === 'keypad' ? 'Types the answer'
  : t.sequenceFrom ? `Slices the answer; slices in order from difficulty ${t.sequenceFrom}` : 'Slices the answer');

/** Strand rows whose year, subject and patterns take this topic. `@pos` in a pattern stands for `shared.pos`. */
export function strandsOf(topic, table) {
  const sub = (s) => new RegExp(s.replaceAll('@pos', table.shared.pos));
  return table.strands.filter(s => s.subject === topic.subject && s.years.includes(topic.year)
    && sub(s.re).test(topic.nc) && !(s.not && sub(s.not).test(topic.nc)));
}

/** Topic ids a `docs/CURRICULUM.md` names as a row: a table row, or a `- id — …` bullet. */
export function curriculumIds(md) {
  return [...md.matchAll(/^(?:[-|]\s*)`?((?:r|y[1-6])-[a-z0-9-]+)`?/gm)].map(m => m[1]);
}

export function buildContentMap({ topics, years, strands, tipFor, banks = {} }) {
  const unmatched = topics.filter(t => !t.nc.trim() || strandsOf(t, strands).length === 0).map(t => t.id);
  if (unmatched.length) throw new Error(`No programme-of-study strand matches the nc of: ${unmatched.join(', ')}. Extend docs/content-map-strands.json.`);
  const rows = topics.map(t => ({
    id: t.id, title: t.title, year: t.year, subject: t.subject, nc: t.nc, mode: modeOf(t), input: t.input ?? 'bubbles',
    difficulties: [1, 2, 3], stages: years.find(y => y.id === t.year).diffs.length,
    questionBank: banks[t.id] ?? 'generated', hasVisual: drawsVisual(t), tip: tipFor(t.id),
    strands: strandsOf(t, strands).map(s => s.id),
  }));
  const byYear = years.map(y => ({
    year: y.id, title: y.title, maths: rows.filter(r => r.year === y.id && r.subject === 'maths').length,
    writing: rows.filter(r => r.year === y.id && r.subject === 'writing').length,
  }));
  const coverage = strands.strands.map(s => ({
    id: s.id, name: s.name, subject: s.subject, years: s.years, source: strands.sources[s.source],
    topics: rows.filter(r => r.strands.includes(s.id)).map(r => r.id),
  }));
  const json = { generated: 'scripts/content-map.mjs', topicCount: rows.length, byYear, topics: rows, coverage };
  return { json: JSON.stringify(json, null, 1) + '\n', md: render(json, years) };
}

const cell = (s) => String(s).replaceAll('|', '\\|');

function render(map, years) {
  const out = [
    '<!-- DO NOT EDIT. Generated by `npm run content-map` from the topic registry and docs/content-map-strands.json. -->',
    '# Content map: what Sharpwise teaches', '',
    `Generated from the registry: ${map.topicCount} topics. A strand counts as covered only when a topic names it. The hand-written rationale stays in [CURRICULUM.md](CURRICULUM.md).`, '',
    '| Year | Maths | English |', '|---|---|---|',
    ...map.byYear.map(y => `| ${y.title} | ${y.maths} | ${y.writing} |`), '',
  ];
  for (const y of years) for (const [subject, label] of [['maths', 'Maths'], ['writing', 'English']]) {
    const rows = map.topics.filter(r => r.year === y.id && r.subject === subject);
    if (!rows.length) continue;
    out.push(`## ${y.title}: ${label}`, '', '| Topic | Objective | Mode | What a child does | Bank | Picture |', '|---|---|---|---|---|---|');
    for (const r of rows) out.push(`| ${cell(r.title)} (\`${r.id}\`) | ${cell(r.nc)} | ${r.mode} | ${howOf(r)} | ${r.questionBank} | ${r.hasVisual ? 'yes' : 'no'} |`);
    out.push('');
  }
  const gaps = map.coverage.filter(c => !c.topics.length);
  out.push('## Coverage of the programmes of study', '',
    `${map.coverage.length - gaps.length} of ${map.coverage.length} strands have at least one topic.`, '',
    '### Not covered yet', '');
  out.push(...(gaps.length ? gaps.map(c => `- ${c.name} ([source](${c.source}))`) : ['None.']), '');
  out.push('### Covered', '', '| Strand | Topics |', '|---|---|');
  for (const c of map.coverage.filter(c => c.topics.length)) out.push(`| ${cell(c.name)} | ${c.topics.length} |`);
  return out.join('\n') + '\n';
}
