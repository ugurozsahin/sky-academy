/**
 * The home page's skip link, header and footer, with only the current-page mark moved to `currentPath`
 * (`site-home.test.ts` holds every page to the home page's shell).
 */
export function shellFrom(home, currentPath) {
  const unmark = (s) => s.replaceAll(' aria-current="page"', '');
  const mark = (s) => s.replace(`<a href="${currentPath}">`, `<a href="${currentPath}" aria-current="page">`);
  return {
    header: mark(unmark(between(home, '<a class="skip"', '</header>'))),
    footer: mark(unmark(between(home, '<footer', '</footer>'))),
  };
}

/** One subject's table for one year, rows grouped by curriculum area in the strand table's order. */
export function subjectTable(map, year, subject) {
  const label = SUBJECTS.find(([id]) => id === subject)[1];
  const rows = map.topics.filter(t => t.year === year.year && t.subject === subject);
  if (!rows.length) return '';
  const out = [
    '<table>',
    `  <caption>${esc(year.title)} ${esc(label)}: ${topicWord(rows.length)}</caption>`,
    '  <thead><tr><th scope="col">Topic</th><th scope="col">Curriculum objective</th></tr></thead>',
  ];
  for (const area of map.coverage.filter(c => c.subject === subject && c.years.includes(year.year))) {
    const inArea = rows.filter(t => t.strands[0] === area.id);
    if (!inArea.length) continue;
    out.push('  <tbody>', `    <tr><th scope="rowgroup" colspan="2">${esc(areaName(area.name))}</th></tr>`);
    for (const t of inArea) out.push(`    <tr><th scope="row">${esc(t.title)}</th><td>${esc(t.nc)}</td></tr>`);
    out.push('  </tbody>');
  }
  out.push('</table>');
  return out.join('\n');
}

/**
 * The parts of this year's programmes of study that no topic of this year names yet. Counted per year: a strand
 * shared by Years 3 and 4 with topics only in Year 4 is a gap in Year 3.
 */
export function gapsOf(map, year) {
  const named = new Set(map.topics.filter(t => t.year === year.year).flatMap(t => t.strands));
  return map.coverage.filter(c => c.years.includes(year.year) && !named.has(c.id));
}

/** A JSON-LD list in the head: a BreadcrumbList on a year page, the ItemList of the years on /curriculum/ (#2161). */
const ldString = (s) => JSON.stringify(s).replaceAll('<', '\\u003c');
const ldList = (type, head, items) => ['  <script type="application/ld+json">', '  {', '    "@context": "https://schema.org",',
  `    "@type": "${type}",`, ...head, '    "itemListElement": [', items.join(',\n'), '    ]', '  }', '  </script>', ''].join('\n');

/** What a year page says a topic practises: the topic's own parent-facing line (#2153), else its objective in plain words, or its area's name when only a code is left. */
export const topicWords = (map, t) => t.parent || plainObjective(t.nc) || areaName(map.coverage.find(c => c.id === t.strands[0]).name);

/**
 * A one-line taste of a year (#2161): the first topic of its first two maths areas and of its first English area,
 * in the year page's plain words. Only the first clause of each, so a `;` inside one never reads as a separator.
 */
export function tasteOf(map, year) {
  const firsts = (subject) => map.coverage.filter(c => c.subject === subject && c.years.includes(year.year))
    .map(c => map.topics.find(t => t.year === year.year && t.subject === subject && t.strands[0] === c.id)).filter(Boolean);
  return [...firsts('maths').slice(0, 2), ...firsts('writing').slice(0, 1)].map(t => topicWords(map, t).split(';')[0].trim());
}

/** One year's card on /curriculum/: its name as the link to its page, its two counts, and the taste. */
const yearCard = (map, y) => `<li><h3><a href="${yearPath(y.year)}">${esc(y.title)}</a></h3>` +
  `<p>${topicWord(y.maths)} in maths and ${topicWord(y.writing)} in English.</p>` +
  `<p>For example: ${tasteOf(map, y).map(esc).join('; ')}.</p></li>`;

/**
 * The whole /curriculum/ page (#2161): a short hub, one card per school year. The topics themselves, their
 * objectives and the gaps live on the year pages (#2160). `home` is website/index.html, the source of the shell.
 */
export function renderCurriculumPage(map, home) {
  const { header, footer } = shellFrom(home, '/curriculum/');
  const url = `${ORIGIN}/curriculum/`;
  const total = (k) => map.byYear.reduce((n, y) => n + y[k], 0);
  const counts = `${total('maths')} in maths and ${total('writing')} in English`;
  const title = 'Curriculum: Sharpwise topics by school year, Reception to Year 6';
  const description = `Sharpwise's ${map.topicCount} maths and English topics, Reception to Year 6, by school year: ${counts}, aligned to the National Curriculum for England.`;
  const intro = section('', [
    '<h1 id="page-title">What Sharpwise covers</h1>',
    `<p class="lede">Sharpwise has ${map.topicCount} maths and English topics, from Reception to Year 6: ${counts}.</p>`,
    '<p>Reception follows the EYFS Early Learning Goals, and Years 1 to 6 are aligned to the National Curriculum for England. This page is made from the game\'s own list of topics, so it changes when the game does.</p>',
    '<p><a class="btn" href="/play/">Play Sharpwise</a></p>',
  ]);
  const years = section('years', [
    '<h2 id="years-title">Pick a school year</h2>',
    '<p>Each year has its own page: every topic in plain words, ideas to try at home, and for teachers the curriculum objective each topic practises.</p>',
    '<ul class="years">',
    ...map.byYear.map(y => `  ${yearCard(map, y)}`),
    '</ul>',
  ]);
  const jsonLd = ldList('ItemList', ['    "name": "Sharpwise topics by school year",', `    "numberOfItems": ${map.byYear.length},`],
    map.byYear.map((y, i) => `      { "@type": "ListItem", "position": ${i + 1}, "name": ${ldString(y.title)}, "url": "${ORIGIN}${yearPath(y.year)}" }`));
  return page({ title, description, url, header, footer, main: [intro, years].map(s => indent(s, 4)).join('\n\n'), jsonLd });
}

/**
 * A spelling pattern opens the objective (`ff, ll`, `ai/ay`, `ch (Greek/French)`, `a before l`, `ough;`), so a
 * capital would misspell it: one or two letters before a comma, slash or bracket, one letter alone, or up to four
 * before a semicolon. `up to 4 digits`, `co-ordination` and `mass/weight` are words and still take the capital.
 */
const LETTER_PATTERN = /^(?:[a-z]{1,2}(?=[,/]| \()|[a-z] |[a-z]{1,4};)/;

/**
 * An objective without the curriculum's shorthand (#2090): the leading `Y3 NPV:`, `ELG Number:` or bare `Y1 `
 * code and any `(3M4)`, `(Appendix 2)`, bare `Appendix 1` or `(Development Matters …)` reference go; the words are
 * the map's own.
 * Returns '' when only a code is left (`E56-25 (App. 1 Y5–6)` gives `E56-25`), so the caller falls back to the area.
 */
export function plainObjective(nc) {
  const words = nc
    .replace(/^(?:ELG|EYFS|Development Matters|Y\d)[^:]{0,30}:\s*/, '')
    .replace(/^Y\d\S*\s+/, '')
    .replace(/\s*\((?:\d+M\d[^)]*|App(?:endix|\.)[^)]*|Development Matters[^)]*)\)/g, '')
    .replace(/\bAppendix \d+\s*/g, '')
    .trim();
  if (!words || /^[A-Z]+\d/.test(words)) return '';
  return LETTER_PATTERN.test(words) ? words : words[0].toUpperCase() + words.slice(1);
}

/** One curriculum area on a year page: its topics in plain words, then each distinct home tip once. */
function areaBlock(map, area, topics) {
  const tips = [...new Set(topics.map(t => t.tip).filter(Boolean))];
  return [
    `<h3>${esc(areaName(area.name))}</h3>`,
    '<dl class="facts">',
    ...topics.map(t => `  <div><dt>${esc(t.title)}</dt><dd>${esc(topicWords(map, t))}</dd></div>`),
    '</dl>',
    ...(tips.length ? ['<p class="note">Try at home:</p>', '<ul>', ...tips.map(tip => `  <li>${esc(tip)}</li>`), '</ul>'] : []),
  ];
}

/** One subject on a year page, its topics grouped by curriculum area in the strand table's order. */
function subjectSection(map, year, subject) {
  const label = SUBJECTS.find(([id]) => id === subject)[1];
  const rows = map.topics.filter(t => t.year === year.year && t.subject === subject);
  if (!rows.length) return '';
  const id = label.toLowerCase();
  const body = [`<h2 id="${id}-title">${label === 'maths' ? 'Maths' : label} in ${esc(year.title)}</h2>`,
    `<p>${topicWord(rows.length)}, grouped by the part of the curriculum each one practises.</p>`];
  for (const area of map.coverage.filter(c => c.subject === subject && c.years.includes(year.year))) {
    const inArea = rows.filter(t => t.strands[0] === area.id);
    if (inArea.length) body.push(...areaBlock(map, area, inArea));
  }
  return section(id, body);
}

const section = (id, body, label) => [
  `<section${!id ? ' aria-labelledby="page-title"' : label ? ` id="${id}" aria-label="${esc(label)}"` : ` id="${id}" aria-labelledby="${id}-title"`}>`,
  '  <div class="wrap">',
  ...body.map(l => `    ${l}`),
  '  </div>',
  '</section>',
].join('\n');

/** Home › Curriculum › this year, for search results (the guides carry the same shape, #1936). */
function breadcrumbs(year) {
  const crumbs = [['Home', '/'], ['Curriculum', '/curriculum/'], [year.title, yearPath(year.year)]];
  return ldList('BreadcrumbList', [], crumbs.map(([name, path], i) => `      { "@type": "ListItem", "position": ${i + 1}, "name": ${ldString(name)}, "item": "${ORIGIN}${path}" }`));
}

/**
 * The teachers' detail on a year page (#2160), collapsed so a parent reads the plain words first: this year's
 * tables from /curriculum/ (`subjectTable`, the same rows) and the parts of the curriculum no topic names yet.
 */
function forTeachers(map, year, framework) {
  const t = esc(year.title), gaps = gapsOf(map, year);
  return section('for-teachers', [
    '<details>',
    '  <summary>For teachers: National Curriculum references and gaps</summary>',
    `  <p>Each ${t} topic with the objective it practises from ${framework}, grouped by curriculum area.</p>`,
    ...SUBJECTS.map(([id]) => subjectTable(map, year, id)).filter(Boolean).flatMap(tb => tb.split('\n')).map(l => `  ${l}`),
    `  <h2 id="not-covered-title">Not covered yet in ${t}</h2>`,
    ...(gaps.length
      ? ['  <p>These parts of the curriculum have no topic in this year yet.</p>', '  <ul>',
        ...gaps.map(c => `    <li>${esc(areaName(c.name))} (${SUBJECTS.find(([id]) => id === c.subject)[1]})</li>`), '  </ul>']
      : ['  <p>Every part of the curriculum listed for this year has at least one topic.</p>']),
    '</details>',
  ], 'For teachers');
}

/** Every year in order, this one marked as the current page, then the years either side of it (#2160). */
function switcher(map, year) {
  const at = map.byYear.findIndex(y => y.year === year.year);
  const link = (y, text = esc(y.title), rel = '') =>
    `<a href="${yearPath(y.year)}"${rel ? ` rel="${rel}"` : ''}${!rel && y.year === year.year ? ' aria-current="page"' : ''}>${text}</a>`;
  const prev = map.byYear[at - 1], next = map.byYear[at + 1];
  return section('years', [
    '<h2 id="years-title">Reception to Year 6</h2>',
    '<nav class="switcher" aria-label="School years">',
    '  <ul>',
    ...map.byYear.map(y => `    <li>${link(y)}</li>`),
    '  </ul>',
    '  <ul>',
    ...(prev ? [`    <li>${link(prev, `Previous: ${esc(prev.title)}`, 'prev')}</li>`] : []),
    ...(next ? [`    <li>${link(next, `Next: ${esc(next.title)}`, 'next')}</li>`] : []),
    '  </ul>',
    '</nav>',
    '<p>All seven years side by side, with their topic counts: <a href="/curriculum/">the curriculum page</a>.</p>',
  ]);
}

/** The page /curriculum/<year>/ (#2090): what a child practises in one school year, in plain words. */
export function renderYearPage(map, year, home) {
  const { header, footer } = shellFrom(home, yearPath(year.year));
  const t = esc(year.title);
  const usesDevMatters = map.topics.some(x => x.year === year.year && x.nc.startsWith('Development Matters'));   // #2154: the sentence follows the map
  const framework = year.year !== 'reception' ? 'the National Curriculum for England'
    : usesDevMatters ? 'the EYFS framework: the Early Learning Goals and Development Matters' : 'the EYFS Early Learning Goals';
  const intro = section('', [
    `<nav aria-label="Breadcrumb"><p><a href="/curriculum/">Curriculum</a> › ${t}</p></nav>`,
    `<h1 id="page-title">${t}: what your child practises</h1>`,
    `<p class="lede">In ${t}, Sharpwise has ${topicWord(year.maths)} in maths and ${topicWord(year.writing)} in English. Each one is below in plain words, with ideas to try at home.</p>`,
    `<p>${t} topics follow ${framework}. This page is made from the game's own list of topics, so it changes when the game does.</p>`,
    '<p><a class="btn" href="/play/">Play Sharpwise</a></p>',
  ]);
  const main = [intro, ...SUBJECTS.map(([id]) => subjectSection(map, year, id)).filter(Boolean),
    forTeachers(map, year, framework), switcher(map, year)].map(s => indent(s, 4)).join('\n\n');
  return page({
    title: `${year.title} maths and English practice game | Sharpwise`,
    description: `What your child practises in ${year.title} with Sharpwise, a free game: ${topicWord(year.maths)} in maths and ${topicWord(year.writing)} in English, in plain words, with ideas to try at home.`,
    url: `${ORIGIN}${yearPath(year.year)}`, header, footer, main, jsonLd: breadcrumbs(year),
  });
}
